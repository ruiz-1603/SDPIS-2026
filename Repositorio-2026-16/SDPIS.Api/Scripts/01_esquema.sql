-- DENUNCIA (núcleo)
-- =====================================================

CREATE TABLE denuncia (
  id_denuncia              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consecutivo              VARCHAR2(60),
  numero_secuencial        NUMBER NOT NULL,
  estado                   VARCHAR2(20) DEFAULT 'PENDIENTE_ASIGNACION'
                            CONSTRAINT CK_DENUNCIA_ESTADO CHECK (estado IN (
                              'PENDIENTE_ASIGNACION','EN_TIEMPO','PRONTA_VENCER',
                              'ATRASADA','EN_REVISION','FINALIZADA')),
  fecha_creacion           DATE DEFAULT SYSDATE NOT NULL,
  area_actual_id           NUMBER NOT NULL,
  funcionario_asignado_id  NUMBER,
  carpeta_confidencial_url    VARCHAR2(500),
  carpeta_no_confidencial_url VARCHAR2(500),
  CONSTRAINT UQ_DENUNCIA_CONSECUTIVO UNIQUE (consecutivo),
  CONSTRAINT FK_DENUNCIA_AREA_ACTUAL FOREIGN KEY (area_actual_id) REFERENCES area(id_area),
  CONSTRAINT FK_DENUNCIA_FUNC_ASIGNADO FOREIGN KEY (funcionario_asignado_id) REFERENCES funcionario(id_funcionario)
);

CREATE INDEX IDX_DENUNCIA_AREA_ACTUAL_ID ON denuncia(area_actual_id);
CREATE INDEX IDX_DENUNCIA_FUNCIONARIO_ASIGNADO_ID ON denuncia(funcionario_asignado_id);

-- atributos propios: 6 (consecutivo, numero_secuencial, estado, fecha_creacion,
--                       carpeta_confidencial_url, carpeta_no_confidencial_url) -> en el límite
-- funcionario_asignado_id = "funcionario encargado" (HU-013), quien trabaja y cierra el caso.
-- El funcionario validador (HU-010/011) queda registrado en evaluacion_criticidad, no aquí,
-- porque puede haber más de una evaluación en el tiempo (re-evaluaciones).

