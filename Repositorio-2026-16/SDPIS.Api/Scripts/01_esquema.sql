-- #####################################################################
-- HU-018: solicitar cierre de denuncia
-- #####################################################################
-- =====================================================
-- SOLICITUD_CIERRE: solicitud formal del funcionario responsable a la
-- jefatura de su area para finalizar la denuncia. 1:N con denuncia: si
-- la jefatura la rechaza (HU-017) se puede volver a solicitar y queda
-- el historial. area_id es la jefatura que evalua (area actual de la
-- denuncia al momento de solicitar).
-- denuncia_cierre queda para la aprobacion en si (HU-017).
-- La fecha de las observaciones finales es fecha_solicitud.
-- =====================================================
DECLARE
  v NUMBER;
BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name = 'SOLICITUD_CIERRE';
  IF v = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE solicitud_cierre (
        id_solicitud_cierre   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        denuncia_id           NUMBER         NOT NULL,
        solicitado_por_id     NUMBER         NOT NULL,
        area_id               NUMBER         NOT NULL,
        resolucion_final      VARCHAR2(2000) NOT NULL,
        observaciones_finales VARCHAR2(2000) NOT NULL,
        acciones_realizadas   VARCHAR2(2000) NOT NULL,
        fecha_solicitud       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        estado                VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL
                              CONSTRAINT CK_SOLICITUD_CIERRE_ESTADO
                              CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA')),
        CONSTRAINT FK_SOL_CIERRE_DENUNCIA
          FOREIGN KEY (denuncia_id) REFERENCES denuncia(id_denuncia),
        CONSTRAINT FK_SOL_CIERRE_SOLICITANTE
          FOREIGN KEY (solicitado_por_id) REFERENCES funcionario(id_funcionario),
        CONSTRAINT FK_SOL_CIERRE_AREA
          FOREIGN KEY (area_id) REFERENCES area(id_area)
      )]';
  END IF;

  -- Indices (B04 -- obligatorios en toda columna FK):
  SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'IDX_SOLICITUD_CIERRE_DENUNCIA_ID';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_SOLICITUD_CIERRE_DENUNCIA_ID ON solicitud_cierre(denuncia_id)';
  END IF;
  SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'IDX_SOLICITUD_CIERRE_SOLICITADO_POR_ID';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_SOLICITUD_CIERRE_SOLICITADO_POR_ID ON solicitud_cierre(solicitado_por_id)';
  END IF;
  -- Bandeja de la jefatura: pendientes de su area, por fecha.
  SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'IDX_SOLICITUD_CIERRE_AREA_ESTADO';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_SOLICITUD_CIERRE_AREA_ESTADO ON solicitud_cierre(area_id, estado, fecha_solicitud)';
  END IF;
  -- A lo sumo UNA solicitud pendiente por denuncia (las aprobadas o
  -- rechazadas no cuentan: el CASE las deja en NULL).
  SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'UQ_SOLICITUD_CIERRE_PENDIENTE';
  IF v = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE UNIQUE INDEX UQ_SOLICITUD_CIERRE_PENDIENTE ON solicitud_cierre(
      CASE WHEN estado = 'PENDIENTE' THEN denuncia_id END)]';
  END IF;
END;
/

-- atributos propios: 5 (resolucion_final, observaciones_finales,
--                       acciones_realizadas, fecha_solicitud, estado)

COMMENT ON TABLE solicitud_cierre IS
  'HU-018: solicitudes de cierre enviadas por el funcionario responsable a la jefatura de su area.';

COMMIT;


