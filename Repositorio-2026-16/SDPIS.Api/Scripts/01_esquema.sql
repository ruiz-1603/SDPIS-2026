CREATE TABLE denunciante (
  id_denunciante NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR2(150),
  correo         VARCHAR2(150),
  telefono       VARCHAR2(20)
);
-- atributos propios: 3

CREATE TABLE tipo_producto (
  id_tipo_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR2(100) NOT NULL,
  activo           CHAR(1) DEFAULT 'S' CHECK (activo IN ('S','N'))
);
-- atributos propios: 2

CREATE TABLE producto (
  id_producto      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR2(200) NOT NULL,
  tipo_producto_id NUMBER,
  activo           CHAR(1) DEFAULT 'S' CHECK (activo IN ('S','N')),
  CONSTRAINT FK_PRODUCTO_TIPO_PRODUCTO FOREIGN KEY (tipo_producto_id) REFERENCES tipo_producto(id_tipo_producto)
);
-- Índices (B04 -- obligatorios en toda columna FK):
CREATE INDEX IDX_PRODUCTO_TIPO_PRODUCTO_ID ON producto(tipo_producto_id);

-- atributos propios: 2

CREATE TABLE region (
  id_region NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR2(100) NOT NULL
);
-- atributos propios: 1

CREATE TABLE area (
  id_area     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR2(150) NOT NULL,
  tipo        VARCHAR2(10) CHECK (tipo IN ('ARS','AR','UVC')),
  codigo_area VARCHAR2(20) NOT NULL,
  region_id   NUMBER,
  CONSTRAINT FK_AREA_REGION FOREIGN KEY (region_id) REFERENCES region(id_region)
);
-- Índices (B04 -- obligatorios en toda columna FK):
CREATE INDEX IDX_AREA_REGION_ID ON area(region_id);

-- atributos propios: 3

CREATE TABLE funcionario (
  id_funcionario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR2(150) NOT NULL,
  rol            VARCHAR2(30) CHECK (rol IN ('validador','jefe_area','superusuario')),
  correo         VARCHAR2(150),
  area_id        NUMBER NOT NULL,
  activo         CHAR(1) DEFAULT 'S' CHECK (activo IN ('S','N')),
  CONSTRAINT FK_FUNCIONARIO_AREA FOREIGN KEY (area_id) REFERENCES area(id_area)
);
-- Índices (B04 -- obligatorios en toda columna FK):
CREATE INDEX IDX_FUNCIONARIO_AREA_ID ON funcionario(area_id);

-- atributos propios: 4

CREATE TABLE criterio (
  id_criterio     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR2(150) NOT NULL,
  tipo_respuesta  VARCHAR2(30) NOT NULL,
  afecta_suma     CHAR(1) DEFAULT 'S' CHECK (afecta_suma IN ('S','N')),
  activo          CHAR(1) DEFAULT 'S' CHECK (activo IN ('S','N'))
);
-- atributos propios: 5
-- Datos esperados (2 criterios puntuables, fórmula confirmada = suma simple, máx 6):
--   UNISTR('Da\00F1o potencial a la salud')          (Bajo=1 / Medio=3 / Alto=5)
--   UNISTR('Criterio t\00E9cnico especializado UVC') (No=0 / Sí=1)
-- "Comercio electrónico" NO es un criterio puntuable, ver evaluacion_criticidad.
CREATE TABLE criterio_valor (
  id_criterio NUMBER NOT NULL,
  valor       VARCHAR2(50) NOT NULL,
  puntaje     NUMBER(5,2) NOT NULL,
  CONSTRAINT PK_CRITERIO_VALOR PRIMARY KEY (id_criterio, valor),
  CONSTRAINT FK_CRITERIO_VALOR_CRITERIO FOREIGN KEY (id_criterio) REFERENCES criterio(id_criterio)
);
-- atributos propios: 1

CREATE TABLE nivel_criticidad (
  nivel       VARCHAR2(20) PRIMARY KEY,
  puntaje_min NUMBER(5,2) NOT NULL,
  puntaje_max NUMBER(5,2) NOT NULL,
  plazo_dias  NUMBER NOT NULL
);
-- atributos propios: 3
-- Rangos confirmados: ALTO 5-6 (60 días) | MEDIO 3-4 (90 días) | BAJO 1-2 (120 días)

