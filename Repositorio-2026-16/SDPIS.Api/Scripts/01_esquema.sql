CREATE TABLE evaluacion_criticidad (
  id_evaluacion                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  denuncia_id                     NUMBER NOT NULL,
  funcionario_validador_id        NUMBER NOT NULL,
  fecha_evaluacion                DATE DEFAULT SYSDATE NOT NULL,
  nivel_criticidad                VARCHAR2(20),
  puntaje_total                   NUMBER(6,2),
  vinculado_comercio_electronico  CHAR(1) CHECK (vinculado_comercio_electronico IN ('S','N')),
  fecha_limite                    DATE,
  -- HU-010: metadata de la evaluacion (misma naturaleza que
  -- vinculado_comercio_electronico), no de un criterio puntual. El numero de
  -- oficio ya no se pide aqui: se registra al reasignar a UVC
  -- (historial_asignacion.numero_oficio).
  observaciones_tecnicas          VARCHAR2(1000),
  CONSTRAINT FK_EVAL_DENUNCIA FOREIGN KEY (denuncia_id) REFERENCES denuncia(id_denuncia),
  CONSTRAINT FK_EVAL_FUNCIONARIO FOREIGN KEY (funcionario_validador_id) REFERENCES funcionario(id_funcionario),
  CONSTRAINT FK_EVAL_NIVEL FOREIGN KEY (nivel_criticidad) REFERENCES nivel_criticidad(nivel)
);
-- Índices (B04 -- obligatorios en toda columna FK):
CREATE INDEX IDX_EVALUACION_CRITICIDAD_DENUNCIA_ID ON evaluacion_criticidad(denuncia_id);
CREATE INDEX IDX_EVALUACION_CRITICIDAD_FUNCIONARIO_VALIDADOR_ID ON evaluacion_criticidad(funcionario_validador_id);
CREATE INDEX IDX_EVALUACION_CRITICIDAD_NIVEL_CRITICIDAD ON evaluacion_criticidad(nivel_criticidad);

-- atributos propios: 5 (fecha_evaluacion, puntaje_total, vinculado_comercio_electronico, fecha_limite,
--                       observaciones_tecnicas)

CREATE TABLE respuesta_criterio (
  id_evaluacion       NUMBER NOT NULL,
  criterio_id         NUMBER NOT NULL,
  valor_seleccionado  VARCHAR2(50) NOT NULL,
  puntaje_obtenido    NUMBER(5,2) NOT NULL,
  CONSTRAINT PK_RESPUESTA_CRITERIO PRIMARY KEY (id_evaluacion, criterio_id),
  CONSTRAINT FK_RESP_CRITERIO_EVAL FOREIGN KEY (id_evaluacion) REFERENCES evaluacion_criticidad(id_evaluacion),
  CONSTRAINT FK_RESP_CRITERIO_VALOR FOREIGN KEY (criterio_id, valor_seleccionado)
      REFERENCES criterio_valor(id_criterio, valor)
);
-- Índices (B04 -- obligatorios en toda columna FK):
CREATE INDEX IDX_RESPUESTA_CRITERIO_CRITERIO_VALOR ON respuesta_criterio(criterio_id, valor_seleccionado);

