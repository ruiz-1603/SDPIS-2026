-- =====================================================
-- DECISION_CIERRE: decision de la jefatura sobre una solicitud de cierre.
-- 1:1 con solicitud_cierre (una decision por solicitud); como la denuncia
-- puede tener varias solicitudes (1:N), solicitud_cierre + decision_cierre
-- forman el historial de decisiones del caso.
--   * decidido_por_id: jefe de area que decidio (usuario); fecha_decision
--     con fecha y hora.
--   * observaciones_jefatura: obligatorias al RECHAZAR, opcionales al APROBAR.
-- La aprobacion en si (quien y cuando finalizo) queda ademas en
-- denuncia_cierre, que estaba reservada para esta HU.
-- =====================================================
DECLARE
  v NUMBER;
BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name = 'DECISION_CIERRE';
  IF v = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE decision_cierre (
        id_decision_cierre     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        solicitud_cierre_id    NUMBER         NOT NULL,
        decidido_por_id        NUMBER         NOT NULL,
        decision               VARCHAR2(20)   NOT NULL
                               CONSTRAINT CK_DECISION_CIERRE_DECISION
                               CHECK (decision IN ('APROBADA','RECHAZADA')),
        observaciones_jefatura VARCHAR2(2000),
        fecha_decision         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT CK_DECISION_CIERRE_OBS
          CHECK (decision = 'APROBADA' OR TRIM(observaciones_jefatura) IS NOT NULL),
        CONSTRAINT UQ_DECISION_CIERRE_SOLICITUD UNIQUE (solicitud_cierre_id),
        CONSTRAINT FK_DEC_CIERRE_SOLICITUD
          FOREIGN KEY (solicitud_cierre_id) REFERENCES solicitud_cierre(id_solicitud_cierre),
        CONSTRAINT FK_DEC_CIERRE_DECIDIDO_POR
          FOREIGN KEY (decidido_por_id) REFERENCES funcionario(id_funcionario)
      )]';
  END IF;

  -- Indices (B04 -- obligatorios en toda columna FK). solicitud_cierre_id
  -- ya queda indexada por UQ_DECISION_CIERRE_SOLICITUD.
  SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'IDX_DECISION_CIERRE_DECIDIDO_POR_ID';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_DECISION_CIERRE_DECIDIDO_POR_ID ON decision_cierre(decidido_por_id)';
  END IF;
END;
/

-- atributos propios: 3 (decision, observaciones_jefatura, fecha_decision)

COMMENT ON TABLE decision_cierre IS
  'HU-017: decision de la jefatura (aprobada/rechazada) sobre cada solicitud de cierre, con usuario, fecha y observaciones.';

