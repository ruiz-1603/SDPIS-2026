  id_periodo          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  funcionario_id      NUMBER NOT NULL,
  motivo              VARCHAR2(30) NOT NULL
                        CONSTRAINT CK_PERIODO_MOTIVO
                        CHECK (motivo IN ('vacaciones','incapacidad','ausencia')),
  fecha_inicio        DATE NOT NULL,
  fecha_fin_estimada  DATE,
  -- Trazabilidad (SRS HU-007): quien registró y cuándo. fecha_registro
  -- se llena con SYSDATE si no se indica.
  registrado_por      VARCHAR2(150),
  fecha_registro      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT FK_PERIODO_FUNCIONARIO
    FOREIGN KEY (funcionario_id) REFERENCES funcionario(id_funcionario)
);

